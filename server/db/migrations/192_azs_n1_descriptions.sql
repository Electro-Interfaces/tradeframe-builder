-- Сеть «АЗС Н1»: описание точки = место (улица в Тюмени, иначе город), как у ГИГ.
-- В 185/191 описание было «АЗС Н1 — АЗС №N», и селектор точек показывал
-- «АЗС №1 - АЗС Н1 — АЗС №1». Меняем только нетронутые описания.

UPDATE trading_points tp
SET description = v.descr
FROM (VALUES
  ('azs-n1-azs-1',  'Амурская'),
  ('azs-n1-azs-2',  'Республики'),
  ('azs-n1-azs-3',  '50 лет ВЛКСМ'),
  ('azs-n1-azs-4',  'Заречный'),
  ('azs-n1-azs-5',  'Институтская'),
  ('azs-n1-azs-6',  'Талица'),
  ('azs-n1-azs-7',  'Новаторов'),
  ('azs-n1-azs-8',  'Ишим'),
  ('azs-n1-azs-9',  '318 км Екатеринбург – Тюмень'),
  ('azs-n1-azs-10', 'Щербакова'),
  ('azs-n1-azs-11', 'Заводоуковск'),
  ('azs-n1-azs-12', '22 км Тюмень – Омск')
) AS v(id, descr)
WHERE tp.id = v.id
  AND tp.description LIKE 'АЗС Н1 — %';
