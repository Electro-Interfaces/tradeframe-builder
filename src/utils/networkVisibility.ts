import type { Network } from "@/types/network";

/**
 * Видна ли сеть в рабочих селекторах/фильтрах данных.
 *
 * Пустые сети (0 точек) скрываются — например БТО после переезда всех станций
 * в ГИГ (и после миграции 162, где БТО остаётся активной, но без точек и
 * external_id). Сеть продолжает существовать в бэке и управляется на странице
 * «Сети и ТТ», но в рабочем интерфейсе (выбор сети для дашбордов/отчётов)
 * не мешает.
 *
 * Намеренно НЕ применяется к админским селекторам назначения прав
 * (MultiNetworkSelect, формы ролей/пользователей) и к странице управления
 * сетями — там нужно видеть все сети.
 */
export function isOperationalNetwork(network: Pick<Network, "pointsCount">): boolean {
  return (network.pointsCount ?? 0) > 0;
}
